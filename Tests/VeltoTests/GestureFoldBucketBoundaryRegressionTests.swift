/// 相邻桶放宽只给多段序列;单段直线 → vs ↗ 必须保持严格(代价 1),
/// 否则水平右滑会误命中斜向直线手势。
@Test func singleSegmentAdjacentBucketsStayStrict() {
  let right = GestureDirection.Signature(sequence: [0], bow: 0)
  let upRight = GestureDirection.Signature(sequence: [7], bow: 0)
  #expect(GestureDirection.distance(right, upRight) == 1)
}

/// 多段序列:每差一个相邻桶记 adjacentSubstitutionCost,除以序列长度。
@Test func multiSegmentAdjacentBucketsCostQuarter() {
  let cost = GestureDirection.adjacentSubstitutionCost
  let drawnDownUp = GestureDirection.Signature(sequence: [2, 6], bow: 0)
  let templateDownUpRight = GestureDirection.Signature(sequence: [2, 7], bow: 0)
  #expect(GestureDirection.distance(drawnDownUp, templateDownUpRight) == cost / 2)

  let drawnUpDown = GestureDirection.Signature(sequence: [6, 2], bow: 0)
  let templateUpRightDownRight = GestureDirection.Signature(sequence: [7, 1], bow: 0)
  #expect(GestureDirection.distance(drawnUpDown, templateUpRightDownRight) == cost)
}

/// 非相邻桶(≥90°)不享受放宽:←→ 与 →← 仍是完全不同的手势。
@Test func oppositeFoldsRemainDistinct() {
  let leftRight = GestureDirection.Signature(sequence: [4, 0], bow: 0)
  let rightLeft = GestureDirection.Signature(sequence: [0, 4], bow: 0)
  #expect(GestureDirection.distance(leftRight, rightLeft) == 1)
}
