/// 确定性抖动(xorshift),让模拟轨迹带上和真鼠标同量级的噪声,又不至于测试飘。
private struct Jitter {
  private var state: UInt64 = 0x9E37_79B9_7F4A_7C15

  mutating func next(amplitude: CGFloat) -> CGFloat {
    state ^= state << 13
    state ^= state >> 7
    state ^= state << 17
    return (CGFloat(state % 2001) / 1000 - 1) * amplitude
  }

  /// 按真实事件的样子抖动并取整。
  mutating func apply(to points: [CGPoint], amplitude: CGFloat = 1.2) -> [CGPoint] {
    points.map { point in
      let x = (point.x + next(amplitude: amplitude)).rounded()
      let y = (point.y + next(amplitude: amplitude)).rounded()
      return CGPoint(x: x, y: y)
    }
  }
}

private func circle(radius: CGFloat, loops: CGFloat, step: CGFloat = 4) -> [CGPoint] {
  let count = Int(2 * .pi * radius * loops / step)
  return (0..<count).map { index in
    let angle = 2 * .pi * loops * CGFloat(index) / CGFloat(count)
    return CGPoint(x: 500 + radius * cos(angle), y: 500 + radius * sin(angle))
  }
}

/// 沿 `heading` 方向来回甩:`strokes` 段,每段长 `amplitude`。
private func shake(amplitude: CGFloat, strokes: Int, heading: CGFloat = 0) -> [CGPoint] {
  let step: CGFloat = 6
  var position = CGPoint(x: 500, y: 500)
  var points = [position]
  for stroke in 0..<strokes {
    let sign: CGFloat = stroke.isMultiple(of: 2) ? 1 : -1
    for _ in 0..<Int(amplitude / step) {
      position.x += sign * step * cos(heading)
      position.y += sign * step * sin(heading)
      points.append(position)
    }
  }
  return points
}

private func cancels(_ points: [CGPoint]) -> Bool {
  guard let first = points.first else { return false }
  var detector = GestureScribbleDetector(at: first)
  for point in points.dropFirst() where detector.update(at: point) {
    return true
  }
  return false
}

private func accumulatedTurn(_ points: [CGPoint]) -> CGFloat {
  guard let first = points.first else { return 0 }
  var detector = GestureScribbleDetector(at: first)
  for point in points.dropFirst() {
    _ = detector.update(at: point)
  }
  return detector.accumulatedTurn
}

@Suite("乱划检测")
struct GestureScribbleDetectorTests {
  private static let realFoldBacks = [
    Traces.seq2Cancelled, Traces.seq5NearMiss, Traces.seq6Cancelled, Traces.seq7Cancelled,
  ]

  @Test("真实长折返不再被判成乱划", arguments: realFoldBacks)
  func realFoldBackIsNotScribble(trace: String) {
    #expect(!cancels(Traces.points(trace)))
  }

  /// 一次折返就转 ≈180°。这条护住「抖动真被滤掉了」:累到 216~371° 那样的值说明
  /// 滞回失效,只是阈值碰巧还没撞上。
  @Test("真实折返的累计转角回到一次反向的量级", arguments: realFoldBacks)
  func realFoldBackAccumulatesOneReversal(trace: String) {
    let degrees = accumulatedTurn(Traces.points(trace)) * 180 / .pi
    #expect((120...200).contains(degrees))
  }

  /// 这几次放过去之后,还得真能认成「置顶」—— 否则只是把取消换成了没匹配。
  @Test("被放行的折返能匹配到置顶", arguments: realFoldBacks)
  func realFoldBackMatchesPinToTop(trace: String) {
    let drawn = GestureDirection.signature(from: Traces.points(trace))
    let pinToTop = GestureDirection.Signature(sequence: [2, 7], bow: 0.510)
    let others = [
      GestureDirection.Signature(sequence: [7, 1], bow: -0.422),
      GestureDirection.Signature(sequence: [2], bow: 0.003),
      GestureDirection.Signature(sequence: [6], bow: 0.014),
    ]
    let distance = GestureDirection.distance(drawn, pinToTop)
    #expect(distance <= 0.34)
    for other in others {
      #expect(distance < GestureDirection.distance(drawn, other))
    }
  }

  @Test("手抖的慢速长折返不被判成乱划")
  func tremblingFoldBackIsNotScribble() {
    var points: [CGPoint] = []
    for y in stride(from: CGFloat(100), to: 800, by: 3) {
      points.append(CGPoint(x: 500 + 2 * sin(y / 9), y: y))
    }
    for y in stride(from: CGFloat(800), to: 100, by: -3) {
      points.append(CGPoint(x: 520 + 2 * sin(y / 9), y: y))
    }
    var jitter = Jitter()
    #expect(!cancels(jitter.apply(to: points, amplitude: 0.6)))
  }

  /// 早期版本把小转角当笔直腿放电,大圈转再多也被清零 —— 大半径这几条就是防它。
  @Test("转圈仍判为乱划", arguments: [CGFloat(20), 40, 80, 150, 300])
  func circleIsScribble(radius: CGFloat) {
    var jitter = Jitter()
    #expect(cancels(jitter.apply(to: circle(radius: radius, loops: 1.3))))
  }

  /// 三段 = 两次反向,正是「来回甩两下」。
  @Test("来回甩两下仍判为乱划", arguments: [CGFloat(40), 80, 150, 300])
  func shakeIsScribble(amplitude: CGFloat) {
    var jitter = Jitter()
    #expect(cancels(jitter.apply(to: shake(amplitude: amplitude, strokes: 3))))
    #expect(cancels(jitter.apply(to: shake(amplitude: amplitude, strokes: 3, heading: 0.7))))
  }

  @Test("直线不判为乱划")
  func straightLineIsNotScribble() {
    var jitter = Jitter()
    #expect(!cancels(jitter.apply(to: shake(amplitude: 900, strokes: 1, heading: 0.3))))
  }
}
